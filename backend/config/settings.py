# Delivery fees per county. Edit these in backend/.env - no code change needed:
#   DELIVERY_FEES_JSON={"Nairobi":300,"Mombasa":200,"Nakuru":300}
#   DEFAULT_DELIVERY_FEE=500
# Any county missing from DELIVERY_FEES_JSON falls back to DEFAULT_DELIVERY_FEE.
DEFAULT_DELIVERY_FEES = {
    "Mombasa": 200,
    "Nairobi": 300,
    "Kisumu": 350,
    "Eldoret": 350,
    "Nakuru": 300,
    "Kiambu": 300,
    "Machakos": 350,
    "Other": 500,
}


def _load_delivery_fees():
    """Read DELIVERY_FEES_JSON from the environment, falling back to the defaults.

    Keys are normalised to Title Case so "nairobi" and "Nairobi" both match.
    """
    raw = os.getenv("DELIVERY_FEES_JSON", "").strip()
    if not raw:
        return dict(DEFAULT_DELIVERY_FEES)
    try:
        parsed = json.loads(raw)
        fees = {
            str(name).strip().title(): int(value)
            for name, value in parsed.items()
            if str(name).strip()
        }
    except (ValueError, TypeError, AttributeError):
        logging.getLogger(__name__).warning(
            "DELIVERY_FEES_JSON is not valid JSON; using built-in defaults."
        )
        return dict(DEFAULT_DELIVERY_FEES)
    if not fees:
        return dict(DEFAULT_DELIVERY_FEES)
    return fees


DELIVERY_FEES = _load_delivery_fees()
DEFAULT_DELIVERY_FEE = int(os.getenv("DEFAULT_DELIVERY_FEE", "500"))
